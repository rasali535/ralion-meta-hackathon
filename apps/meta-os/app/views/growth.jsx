import {ArrowRight,TrendingUp} from 'lucide-react';
import {missionStatus} from '../../lib/navigation';
import {Badge,Card,Rows,EmptyState,ModeBadge,Banner,LiveErrorBanner} from '../components/ui';

export default function GrowthView({mission,onNavigate}){
  const status=missionStatus(mission);
  if(status.presence==='none'){
    return <div className="page">
      <div className="page-head"><h1>Growth</h1><p className="lede">Opportunities, strategies and campaign proposals.</p></div>
      <EmptyState icon={TrendingUp} title="No growth plan yet" body="Growth planning starts from a mission with a clear objective and audience." action={<button type="button" className="btn primary" onClick={()=>onNavigate('business')}>Create a mission <ArrowRight size={16}/></button>} />
    </div>;
  }
  const m=mission;
  return <div className="page">
    <div className="page-head"><div className="row"><h1>Growth</h1><ModeBadge status={status}/></div><p className="lede">Evidence-informed opportunity discovery and campaign planning for {m.business.name}.</p></div>
    <LiveErrorBanner code={status.liveError}/>
    <Banner tone="info">Strategy drafts only. No execution is connected, and no results exist until a real authorized campaign runs.</Banner>
    <Card title="Opportunity" sub="Testable campaign hypothesis.">
      <div className="row"><Badge tone="muted">{String((m.growth&&m.growth.category)||'MARKETING_ACQUISITION').replace(/_/g,' ')}</Badge></div>
      <Rows items={[
        {k:'Opportunity',v:m.growth.opportunity},
        {k:'Rationale',v:m.growth.reason},
        {k:'Measurement',v:m.growth.measurement},
        {k:'Current results',v:'No measured results available'},
      ]}/>
    </Card>
    {status.live&&<Card title="AI diagnosis" sub={'Generated by '+String(m.mariReasoning.model)}>
      <p>{String(m.mariReasoning.output).slice(0,600)}{String(m.mariReasoning.output).length>600?'…':''}</p>
    </Card>}
  </div>;
}
