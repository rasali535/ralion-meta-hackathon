import {ArrowRight,TrendingUp,Palette,Megaphone} from 'lucide-react';
import {missionStatus} from '../../lib/navigation';
import {Badge,Card,Rows,EmptyState,ModeBadge,Banner,LiveErrorBanner} from '../components/ui';

export default function GrowthView({mission,onNavigate,onSendBrief}){
  const status=missionStatus(mission);
  if(status.presence==='none'){
    return <div className="page">
      <div className="page-head"><h1>Growth</h1><p className="lede">Opportunities, strategies and campaign proposals.</p></div>
      <EmptyState icon={TrendingUp} title="No growth plan yet" body="Growth planning starts from a mission with a clear objective and audience." action={<button type="button" className="btn primary" onClick={()=>onNavigate('business')}>Create a mission <ArrowRight size={16}/></button>} />
    </div>;
  }
  const m=mission;
  const channels=Array.isArray(m.social)?m.social.map(s=>s.channel).filter(Boolean):[];
  return <div className="page">
    <div className="page-head"><div className="row"><h1>Growth</h1><ModeBadge status={status}/></div><p className="lede">Evidence-informed opportunity discovery and campaign planning for {m.business.name}.</p></div>
    <LiveErrorBanner code={status.liveError}/>
    <Banner tone="info">Strategy drafts only. No execution is connected, and no results exist until a real authorized campaign runs.</Banner>
    <Card title="Priority opportunity" sub="The one testable move MARI recommends first." action={<Badge tone="muted">{String((m.growth&&m.growth.category)||'MARKETING_ACQUISITION').replace(/_/g,' ')}</Badge>}>
      <Rows items={[
        {k:'Opportunity',v:m.growth.opportunity},
        {k:'Intended audience',v:m.business.audience},
        {k:'Channels',v:channels.length>0?channels.join(' · ')+' (drafts only)':'No channel drafts yet'},
        {k:'Rationale',v:m.growth.reason},
        {k:'Hypothesis',v:'If this campaign runs for the test window, qualified enquiries will respond measurably. Unproven until real execution.'},
        {k:'Measurement',v:m.growth.measurement},
        {k:'Current results',v:'No measured results available'},
      ]}/>
    </Card>
    <Card title="Supporting evidence" sub="What this recommendation stands on.">
      <Rows items={[
        {k:'Website retrieval',v:String(m.evidence.websiteStatus).replace(/_/g,' ')},
        {k:'Verified text',v:m.evidence.site?String(m.evidence.site.wordCount)+' words · '+String(m.evidence.site.contentHash).slice(0,24)+'…':'None — profile claims only'},
        {k:'Business facts',v:m.business.facts?'User-supplied, unverified':'Not provided'},
        {k:'Reasoning basis',v:status.live?('Live '+String(m.mariReasoning.model)+' output from unverified claims'):'Deterministic demo hypothesis'},
      ]}/>
    </Card>
    <Card title="Proposed next actions" sub="Handoffs stay inside the workspace until a human approves.">
      <div className="row">
        <button type="button" className="btn primary" onClick={()=>onSendBrief&&onSendBrief()}><Palette size={15}/> Send brief to Creative Studio</button>
        <button type="button" className="btn ghost" onClick={()=>onNavigate('social')}><Megaphone size={15}/> Review social drafts</button>
      </div>
      <p className="muted" style={{marginTop:10}}>The creative brief carries this opportunity, audience, and objective into image generation. Nothing generates without explicit confirmation.</p>
    </Card>
    {status.live&&<Card title="AI diagnosis" sub={'Generated by '+String(m.mariReasoning.model)}>
      <p>{String(m.mariReasoning.output).slice(0,600)}{String(m.mariReasoning.output).length>600?'…':''}</p>
    </Card>}
  </div>;
}
