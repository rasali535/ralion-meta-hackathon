import {ArrowRight,BrainCircuit} from 'lucide-react';
import {WORKFLOW_STEPS,missionStatus,stepState} from '../../lib/navigation';
import {Card,Rows,EmptyState,Stepper,Stat,ModeBadge,ProgressBar,LiveErrorBanner} from '../components/ui';

function stepView(id){return id==='approval'?'activity':id;}

export default function CommandView({mission,onNavigate}){
  const status=missionStatus(mission);
  if(status.presence==='none'){
    return <div className="page">
      <div className="page-head"><h1>Command Centre</h1><p className="lede">Missions, evidence and AI activity for this workspace, in one place.</p></div>
      <EmptyState icon={BrainCircuit} title="No mission yet" body="Create a business profile and send your first mission to MARI. Every step stays visible here, from evidence to approval." action={<button type="button" className="btn primary" onClick={()=>onNavigate('business')}>Create a mission <ArrowRight size={16}/></button>} />
    </div>;
  }
  const m=mission;
  const done=WORKFLOW_STEPS.filter(s=>stepState(s.id,m)==='done').length;
  const aiText=status.live?String(m.mariReasoning.output):'';
  return <div className="page">
    <div className="page-head"><div className="row"><h1>Command Centre</h1><ModeBadge status={status}/></div><p className="lede">{m.business.name} · Mission {String(m.missionId).slice(0,8)}</p></div>
    <LiveErrorBanner code={status.liveError}/>
    <div className="stats">
      <Stat label="Reasoning" value={status.live?'Live AI':'Demo'} sub={status.live?String(m.mariReasoning.model):'Deterministic plan'}/>
      <Stat label="Evidence" value={status.hasEvidence?'Retrieved':'Reference'} sub={status.hasEvidence?String(m.evidence.site.wordCount)+' words verified':'No page fetched'}/>
      <Stat label="Approval" value={status.approval.replace(/_/g,' ')} sub="Human review required"/>
      <Stat label="Workflow" value={done+' / 6'} sub="Stages ready"/>
    </div>
    <Card title="Mission workflow" sub="Select a stage to open it.">
      <Stepper steps={WORKFLOW_STEPS} stateFor={(id)=>stepState(id,m)} onStep={(id)=>onNavigate(stepView(id))}/>
      <ProgressBar value={done} max={6}/>
    </Card>
    <div className="grid-2">
      <Card title="Latest insight" sub={status.live?'Generated by '+String(m.mariReasoning.model):'Deterministic hypothesis'} action={<button type="button" className="btn small ghost" onClick={()=>onNavigate('mari')}>Open MARI <ArrowRight size={14}/></button>}>
        <p>{status.live?(aiText.slice(0,320)+(aiText.length>320?'…':'')):m.growth.reason}</p>
      </Card>
      <Card title="Business" sub={m.business.industry} action={<button type="button" className="btn small ghost" onClick={()=>onNavigate('business')}>Open Business <ArrowRight size={14}/></button>}>
        <Rows items={[{k:'Objective',v:m.business.objective},{k:'Audience',v:m.business.audience},{k:'Website',v:m.business.website||'Not provided'}]}/>
      </Card>
    </div>
    <p className="footer-note">Drafts only. No campaigns publish, no ad spend, and no external actions run from this workspace.</p>
  </div>;
}
