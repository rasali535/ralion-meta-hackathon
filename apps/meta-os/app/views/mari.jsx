import {ArrowRight,BrainCircuit} from 'lucide-react';
import {WORKFLOW_STEPS,missionStatus,stepState} from '../../lib/navigation';
import {Badge,Card,Rows,EmptyState,Stepper,ModeBadge,LiveErrorBanner} from '../components/ui';

function stepView(id){return id==='approval'?'activity':id;}
function planRows(m){
  return [
    {k:'Insight',v:m.growth.reason},
    {k:'Hypothesis',v:m.growth.opportunity},
    {k:'Recommended action',v:m.growth.measurement},
    {k:'Approval required',v:'Yes — human review before any external step'},
  ];
}

export default function MariView({mission,onNavigate}){
  const status=missionStatus(mission);
  if(status.presence==='none'){
    return <div className="page">
      <div className="page-head"><h1>MARI</h1><p className="lede">Reasoning, missions and recommended actions, grounded in your business context.</p></div>
      <EmptyState icon={BrainCircuit} title="MARI is waiting for a mission" body="Send a business profile first. MARI will connect it to Growth, Creative and Social as one reviewable mission." action={<button type="button" className="btn primary" onClick={()=>onNavigate('business')}>Create a mission <ArrowRight size={16}/></button>} />
    </div>;
  }
  const m=mission;
  return <div className="page">
    <div className="page-head"><div className="row"><h1>MARI</h1><ModeBadge status={status}/></div><p className="lede">{m.business.name} · {status.live?'Live model diagnosis with a deterministic draft beside it.':'Deterministic analysis. Request live AI from the Business workspace.'}</p></div>
    <LiveErrorBanner code={status.liveError}/>
    <Stepper steps={WORKFLOW_STEPS} stateFor={(id)=>stepState(id,m)} onStep={(id)=>onNavigate(stepView(id))}/>
    {status.live?<Card title="Live AI diagnosis" sub={'Generated by '+String(m.mariReasoning.model)} action={<Badge tone="live">Live</Badge>}>
      <Rows items={[
        {k:'Model',v:<span className="mono">{String(m.mariReasoning.model)}</span>},
        {k:'Request',v:<span className="mono">{String(m.mariReasoning.requestId||'—')}</span>},
        {k:'Evidence basis',v:'Model output from unverified user-supplied claims'},
        {k:'Workspace',v:<span className="mono">{String(m.mariReasoning.organizationId||'—')} / {String(m.mariReasoning.workspaceId||'—')}</span>},
      ]}/>
      <pre className="code">{m.mariReasoning.output}</pre>
    </Card>:<Card title="Analysis" sub="Deterministic demo reasoning" action={<Badge tone="demo">Demo</Badge>}>
      <Rows items={planRows(m)}/>
    </Card>}
    {status.live&&<Card title="Plan draft" sub="Deterministic draft kept alongside the AI diagnosis.">
      <Rows items={planRows(m)}/>
    </Card>}
    <Card title="Approval" sub="External steps need explicit human sign-off.">
      <Rows items={[
        {k:'Status',v:String(m.approval.status).replace(/_/g,' ')},
        {k:'Scope',v:'Approvals in this build cover local drafts only'},
        {k:'Publishing',v:'Not connected — nothing can publish or spend'},
      ]}/>
    </Card>
  </div>;
}
