import {useState} from 'react';
import {ArrowRight,BrainCircuit,Send} from 'lucide-react';
import {missionStatus} from '../../lib/navigation';
import {Badge,Card,Rows,EmptyState,ModeBadge,LiveErrorBanner} from '../components/ui';

function planRows(m){
  return [
    {k:'Insight',v:m.growth.reason},
    {k:'Hypothesis',v:m.growth.opportunity},
    {k:'Recommended action',v:m.growth.measurement},
    {k:'Approval required',v:'Yes — human review before any external step'},
  ];
}

export default function MariView({mission,onNavigate,onFollowup}){
  const status=missionStatus(mission);
  const [followup,setFollowup]=useState('');
  if(status.presence==='none'){
    return <div className="page">
      <div className="page-head"><h1>MARI</h1><p className="lede">Reasoning, missions and recommended actions, grounded in your business context.</p></div>
      <EmptyState icon={BrainCircuit} title="MARI is waiting for a mission" body="Send a business profile first. MARI will connect it to Growth, Creative and Social as one reviewable mission." action={<button type="button" className="btn primary" onClick={()=>onNavigate('business')}>Create a mission <ArrowRight size={16}/></button>} />
    </div>;
  }
  const m=mission;
  const site=m.evidence&&m.evidence.site?m.evidence.site:null;
  function ask(e){
    e.preventDefault();
    if(onFollowup&&followup.trim()){onFollowup(followup.trim());setFollowup('');}
  }
  return <div className="page">
    <div className="page-head"><div className="row"><h1>MARI</h1><ModeBadge status={status}/>{status.live?<Badge tone="ai">{String(m.mariReasoning.model)}</Badge>:null}</div><p className="lede">{m.business.name} · {status.live?'Live model diagnosis with a deterministic draft beside it.':'Deterministic analysis. Request live AI from the Business workspace.'}</p></div>
    <LiveErrorBanner code={status.liveError}/>
    <div className="grid-2">
      <Card title="Business context" sub="What MARI was allowed to reason about.">
        <Rows items={[
          {k:'Business',v:m.business.name+' · '+m.business.industry},
          {k:'Objective',v:m.business.objective},
          {k:'Audience',v:m.business.audience},
          {k:'Facts basis',v:m.business.facts?'User-supplied, unverified':'Not provided'},
          ...(m.business.facts&&m.business.facts.includes('Follow-up:')?[{k:'Follow-up note',v:m.business.facts.split('Follow-up: ').pop()}]:[]),
        ]}/>
      </Card>
      <Card title="Verified evidence" sub="Retrieved server-side, never assumed.">
        {site?<Rows items={[
          {k:'Source',v:<span className="mono">{site.finalUrl}</span>},
          {k:'Retrieval',v:String(m.evidence.websiteStatus).replace(/_/g,' ')},
          ...(site.renderedVia==='reader'?[{k:'Render method',v:'Rendered text via reader service'}]:[]),
          {k:'Size',v:String(site.wordCount)+' words'},
          {k:site.renderedVia==='reader'?'Text hash (rendered)':'Content hash',v:<span className="mono">{String(site.contentHash).slice(0,24)+'…'}</span>},
        ]}/>:<p className="muted">No page text was retrieved. Status: {String(m.evidence.websiteStatus).replace(/_/g,' ')}. MARI worked from your supplied profile only.</p>}
      </Card>
    </div>
    {status.live?<Card title="Live AI diagnosis" sub={'Generated by '+String(m.mariReasoning.model)} action={<Badge tone="live">Live</Badge>}>
      <Rows items={[
        {k:'Request',v:<span className="mono">{String(m.mariReasoning.requestId||'Not reported')}</span>},
        {k:'Evidence basis',v:'Model output from unverified user-supplied claims'},
        {k:'Workspace',v:<span className="mono">{String(m.mariReasoning.organizationId||'—')} / {String(m.mariReasoning.workspaceId||'—')}</span>},
      ]}/>
      <pre className="code">{m.mariReasoning.output}</pre>
    </Card>:<Card title="Analysis" sub="Deterministic demo reasoning" action={<Badge tone="demo">Demo</Badge>}>
      <Rows items={planRows(m)}/>
    </Card>}
    {status.live&&<Card title="Plan draft" sub="Deterministic draft kept alongside the AI diagnosis.">
      <Rows items={planRows(m)}/>
    </Card>}
    <Card title="Ask a follow-up" sub="Your note is added to the business facts and the mission is planned again as a new revision.">
      <form className="hero-goal" onSubmit={ask}>
        <input className="input" value={followup} onChange={e=>setFollowup(e.target.value)} maxLength={500} placeholder="e.g. Focus on weekend foot traffic instead" aria-label="Follow-up question for MARI"/>
        <button type="submit" className="btn primary" disabled={!followup.trim()}><Send size={15}/> Ask follow-up</button>
      </form>
    </Card>
    <Card title="Reasoning mode" sub="How this mission was planned, and how to change it.">
      <Rows items={[
        {k:'Current mode',v:status.live?('Live · '+String(m.mariReasoning.model)+(m.mariReasoning.mode?' ('+m.mariReasoning.mode+')':'')):'Deterministic demo'},
        {k:'Change mode',v:'Edit the Business profile, toggle live diagnosis, pick Spark or Wonder, and resend the mission'},
        {k:'Approval status',v:String(m.approval.status).replace(/_/g,' ')},
        {k:'Publishing',v:'Not connected — nothing can publish or spend'},
      ]}/>
    </Card>
  </div>;
}
